-- 5. Verificar tabla audit_logs (puede que no exista)
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    usuario TEXT,
    rol TEXT,
    sucursal TEXT,
    accion TEXT NOT NULL,
    detalles TEXT
);
ALTER TABLE public.audit_logs DISABLE ROW LEVEL SECURITY;

-- 6. Verificar tabla cash_shifts
CREATE TABLE IF NOT EXISTS public.cash_shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sucursal TEXT NOT NULL,
    estado TEXT DEFAULT 'abierta',
    abierto_por TEXT,
    monto_inicial NUMERIC DEFAULT 0,
    monto_final NUMERIC,
    cerrado_por TEXT,
    opened_at TIMESTAMPTZ DEFAULT NOW(),
    closed_at TIMESTAMPTZ,
    notas TEXT
);
ALTER TABLE public.cash_shifts DISABLE ROW LEVEL SECURITY;

-- 7. Asegurar columna categoria en cash_withdrawals
ALTER TABLE public.cash_withdrawals ADD COLUMN IF NOT EXISTS categoria TEXT DEFAULT 'Gasto Local';

-- 8. Grant permisos completos al rol anon (necesario para que funcione sin autenticación)
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon;
GRANT USAGE ON SCHEMA public TO anon;

-- 9. Verificar estructura de repairs con SELECT
SELECT column_name, data_type, is_nullable 
FROM information_schema.columns 
WHERE table_schema = 'public' AND table_name = 'repairs'
ORDER BY ordinal_position;

-- 10. Verificar que no hay datos corruptos en repairs
SELECT id, estado, sucursal, sucursal_admit FROM public.repairs ORDER BY created_at DESC LIMIT 20;
